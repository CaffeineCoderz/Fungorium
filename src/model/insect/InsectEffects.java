package insect;

/**
 * Enum to represent the different effects that can be applied to an insect.
 * NORMAL: no effect
 * STUN: the insect is stunned and cannot move
 * NO_CUT: the insect cannot cut threads
 * FAST: the insect moves faster
 * SLOW: the insect moves slower
 */
public enum InsectEffects {
    NORMAL, STUN, NO_CUT, FAST, SLOW
}
